# Ruby Marshal 4.8 最小读写
# ================================================================
class MarshalError(Exception):
    pass


def _w_long(n):
    """Marshal 的 long 编码。"""
    if n == 0:
        return b"\x00"
    if 0 < n < 123:
        return bytes([n + 5])
    out = b""
    x = n
    while x:
        out += bytes([x & 0xFF])
        x >>= 8
    return bytes([len(out)]) + out


def _r_long(data, i):
    b = data[i]
    if b == 0:
        return 0, i + 1
    if b > 0:
        if b < 123 + 5 and b >= 5:      # 单字节正数：值 = b - 5
            return b - 5, i + 1
        # 多字节
        n = b
        val = int.from_bytes(data[i + 1:i + 1 + n], "little")
        return val, i + 1 + n
    # 负数（-124 < x < 0 → 251 + x）
    if b >= 0xFB - 123:
        return b - 0xFB, i + 1
    n = -b
    val = int.from_bytes(data[i + 1:i + 1 + n], "little", signed=True)
    return val, i + 1 + n


class _MReader:
    """只解析 Scripts.rxdata 会出现的类型。"""

    def __init__(self, data):
        self.data = data
        self.symbols = []
        self.i = 0

    def byte(self):
        b = self.data[self.i]
        self.i += 1
        return b

    def long_(self):
        v, self.i = _r_long(self.data, self.i)
        return v

    def parse(self):
        if self.data[self.i:self.i + 2] == b"\x04\x08":
            self.i += 2
        return self.object_()

    def object_(self):
        t = self.byte()
        c = chr(t)
        if c == "0":
            return None
        if c == "T":
            return True
        if c == "F":
            return False
        if c == "i":
            return self.long_()
        if c == ":":                      # symbol
            n = self.long_()
            raw = self.data[self.i:self.i + n]
            self.i += n
            sym = ":" + raw.decode("utf-8", "replace")
            self.symbols.append(sym)
            return sym
        if c == ";":                      # symlink
            idx = self.long_()
            return self.symbols[idx]
        if c == '"':                      # string（保留原始字节！）
            n = self.long_()
            raw = self.data[self.i:self.i + n]
            self.i += n
            return raw
        if c == "I":                      # ivar 扩展对象（字符串 + 编码等）
            obj = self.object_()
            cnt = self.long_()
            for _ in range(cnt):
                self.object_()            # key（:E 等）
                self.object_()            # value（T / 编码名符号）
            return obj
        if c == "[":                      # array
            n = self.long_()
            return [self.object_() for _ in range(n)]
        raise MarshalError(f"不支持的 Marshal 类型：{c!r}（偏移 {self.i - 1}）")


def _w_str(s):
    raw = s.encode("utf-8") if isinstance(s, str) else s
    # I + " + len + bytes + ivar(1) + :E + T(UTF-8)
    return (b'I"' + _w_long(len(raw)) + raw
            + b"\x06:\x06E" + b"T")


def marshal_dump_scripts(entries):
    """
    序列化 [[id, title, code], ...] 为 Marshal 字节
    （带 \\x04\\x08 头，字符串都标 UTF-8 编码，避免 Ruby 3.x 里
    纯 Marshal 字符串默认 US-ASCII 引发编码不兼容）。
    title / code 可以是 str（自动 UTF-8 编码）或 bytes（原样写入，
    用于已经 zlib 压缩过的脚本）。
    """
    out = b"\x04\x08["
    out += _w_long(len(entries))
    for id_, title, code in entries:
        out += b"[" + _w_long(3)
        out += b"i" + _w_long(int(id_))
        out += _w_str(str(title))
        out += _w_str(code)
        out += b"]"
    return out


def marshal_load_scripts(path):
    """
    读取 Scripts.rxdata，返回 [[id, title(str), code(str)], ...]。

    ★ rxdata 里第三项是 zlib 压缩的脚本源码，必须先解压再解码；
       少数未压缩的条目（如空脚本）原样按文本处理。
    """
    with open(path, "rb") as f:
        data = f.read()
    r = _MReader(data)
    obj = r.parse()
    if not isinstance(obj, list):
        raise MarshalError("Scripts.rxdata 顶层不是数组")
    out = []
    for e in obj:
        if not isinstance(e, list) or len(e) < 3:
            continue
        sid, title, code = e[0], e[1], e[2]
        if isinstance(sid, bytes):
            sid = sid.decode("utf-8", "replace")
        if isinstance(title, bytes):
            title = title.decode("utf-8", "replace")
        if isinstance(code, bytes):
            try:
                code = zlib.decompress(code)
            except zlib.error:
                pass                      # 未压缩的条目
            code = code.decode("utf-8", "replace")
        try:
            sid = int(sid)
        except (TypeError, ValueError):
            sid = 0
        out.append([sid, str(title), str(code)])
    return out


