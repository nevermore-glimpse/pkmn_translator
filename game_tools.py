# ② 删条件：把「只有 $DEBUG 为真才生效」的判断去掉
_COND_PATS = [
    (re.compile(r"\bif\s+!\$DEBUG\s+&&\s+"), "if "),
    (re.compile(r"\bif\s+\$DEBUG\s+&&\s+"), "if "),
    (re.compile(r"\bif\s+\$DEBUG\s*\|\|\s*"), "if "),
    (re.compile(r"\bif\s+!\$DEBUG\b"), "if false"),
    (re.compile(r"\bif\s+\$DEBUG\b"), "if true"),
    (re.compile(r"\bunless\s+\$DEBUG\b"), "unless false"),
    (re.compile(r"\bif\s+!\$TEST\b"), "if false"),
    (re.compile(r"\bif\s+\$TEST\b"), "if true"),
]


def _strip_debug_conditions(game_dir):
    """
    ② 删掉 $DEBUG / $TEST 条件：穿墙、调试菜单、宝可梦调试等
    「只有调试模式才生效」的分支改成无条件执行。
    返回修改说明列表。
    """
    scripts_dir = _scripts_dir(game_dir)
    skip_prefix = (DEBUG_SCRIPT_NAME, "~zz_")
    mods = []
    for path in _rb_files(scripts_dir):
        name = os.path.basename(path)
        if name.startswith(skip_prefix):
            continue
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as f:
                text = f.read()
        except Exception:
            continue
        if "$DEBUG" not in text and "$TEST" not in text:
            continue
        new_text = text
        total = 0
        for pat, rep in _COND_PATS:
            new_text, n = pat.subn(rep, new_text)
            total += n
        # ★ 清理冗余：if false || X → if X；if true && X → if X；
        #   X && true / X || false → X；末尾的 if true 直接去掉
        for pat, rep in (
                (re.compile(r"\b(if|unless)\s+false\s*\|\|\s*"), r"\1 "),
                (re.compile(r"\b(if|unless)\s+true\s*&&\s*"), r"\1 "),
                (re.compile(r"\s*&&\s*true\b"), ""),
                (re.compile(r"\s*\|\|\s*false\b"), ""),
                (re.compile(r"\btrue\s*&&\s*"), ""),
                (re.compile(r"\bfalse\s*\|\|\s*"), ""),
                (re.compile(r"\s+if\s+true\s*$", re.MULTILINE), ""),
        ):
            new_text = pat.sub(rep, new_text)
        if not total or new_text == text:
            continue
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(new_text)
        mods.append({
            "file": _rel(path, scripts_dir),
            "how": "条件改写",
            "change": f"把 {total} 处 $DEBUG / $TEST 判断改成无条件"
                      f"（if $DEBUG → if true，if !$DEBUG → if false）",
        })
        log.info("删条件：%s 共 %d 处", name, total)
    return mods


def _inject_repel(game_dir):
    """
    ③ 把「是否开启调试」注入 100 步除虫喷雾（:REPEL）。
    注入点选在 proc 最开头 → 先于「上一瓶还有步数」的检查执行，
    所以无论是否还有步数残留都会弹提示。
    """
    scripts_dir = _scripts_dir(game_dir)
    pats = [
        re.compile(r"[ \t]*ItemHandlers::UseInField\.add\(\s*:REPEL\s*,\s*"
                   r"(?:proc|lambda)\s*\{[^\n|]*\|[^\n]*"),
        re.compile(r"[ \t]*ItemHandlers::UseInField\.add\(\s*:REPEL\s*,"
                   r"[^\n]*\{\s*\|[^\n]*"),
        re.compile(r"[ \t]*ItemHandlers::UseInField\.add\(\s*:REPEL\s*,"
                   r"[^\n]*do\s*\|[^\n]*"),
    ]
    for path in _rb_files(scripts_dir):
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as f:
                text = f.read()
        except Exception:
            continue
        for pat in pats:
            m = pat.search(text)
            if not m:
                continue
            if REPEL_INJECT_CODE.strip()[:40] in text:
                return [{
                    "file": _rel(path, scripts_dir),
                    "how": "已存在（本次保留）",
                    "change": "除虫喷雾注入块已在文件中",
                }]
            new_text = (text[:m.end()] + "\n" + REPEL_INJECT_CODE
                        + text[m.end():])
            with open(path, "w", encoding="utf-8", newline="") as f:
                f.write(new_text)
            log.info("除虫喷雾注入：%s", _rel(path, scripts_dir))
            return [{
                "file": _rel(path, scripts_dir),
                "how": "注入到 :REPEL（100 步除虫喷雾）处理块开头",
                "change": "使用 100 步除虫喷雾时询问是否开启调试"
                          "（先于「还有步数」检查，残留步数也能触发）",
            }]
    return []


