def _plugin_copied_font(game_dir):
    """
    读插件 Settings 里的「# Copied font: xxx.ttf」标记，返回当初复制进
    Fonts 的字体文件名；没有标记（或没植入过）返回 None。
    """
    p = os.path.join(_scripts_dir(game_dir), PLUGIN_SETTINGS_NAME)
    if not os.path.isfile(p):
        return None
    try:
        with open(p, "r", encoding="utf-8", errors="replace") as f:
            for line in f:
                if line.startswith("# Copied font:"):
                    return line.split(":", 1)[1].strip() or None
    except Exception as e:
        log.warning("读取插件 Settings 失败：%s", e)
    return None


def _remove_copied_font(game_dir, font_name, say):
    """删掉当初复制进游戏 Fonts 的那份字体（游戏自带字体不会命中标记）。"""
    if not font_name:
        return False
    fp = os.path.join(game_dir, "Fonts", font_name)
    if not os.path.isfile(fp):
        return False
    try:
        os.remove(fp)
        say(f"[还原] 已删除 Fonts/{font_name}")
        return True
    except Exception as e:
        say(f"[还原] 删除 Fonts/{font_name} 失败：{e}")
        return False


def restore_injection(game_dir, emit=None):
    """
    还原「注入操作」：把工具改过的脚本恢复成解包时的样子。
    有备份 → 用 ScriptsBackup.rxdata 重新生成 Data/Scripts（最干净）；
    没备份 → 退而求其次，删掉工具注入的那几个文件。
    返回 dict。
    """
    def say(msg):
        if emit:
            emit(msg)

    backup = os.path.join(game_dir, "Data", "ScriptsBackup.rxdata")
    font_name = _plugin_copied_font(game_dir)      # ★ 重建目录前先记下字体名
    if os.path.exists(backup):
        n, path, _ = dump_scripts(game_dir, emit=emit, force=True)
        say(f"[还原] 已按备份重新生成脚本：{n} 个文件（注入内容已清除）")
        removed_font = _remove_copied_font(game_dir, font_name, say)
        return {"ok": True, "how": "backup", "files": n,
                "font_removed": removed_font}

    scripts_dir = _scripts_dir(game_dir)
    if not os.path.isdir(scripts_dir):
        raise FileNotFoundError("没有 Data/Scripts 目录，也没有备份，无从还原")

    removed = []
    for f in _rb_files(scripts_dir):
        base = os.path.basename(f)
        if base.startswith("000_") or base.startswith("~zz_"):
            try:
                os.remove(f)
                removed.append(_rel(f, scripts_dir))
            except Exception as e:
                log.warning("删除注入文件失败 %s：%s", f, e)
    if removed:
        say(f"[还原] 已删除工具注入的文件 {len(removed)} 个")
    else:
        say("[还原] 没找到工具注入的文件（可能已经还原过）")
    say("[还原] ⚠ 没有备份，被改写过的游戏脚本无法自动恢复，"
        "建议重新解包或重装游戏")
    removed_font = _remove_copied_font(game_dir, font_name, say)
    return {"ok": bool(removed), "how": "files", "files": removed,
            "font_removed": removed_font}


def restore_extraction(game_dir, emit=None):
    """
    还原「提取脚本」：删掉 Data/Scripts 目录，把备份改回 Scripts.rxdata，
    游戏回到未解包状态。
    """
    def say(msg):
        if emit:
            emit(msg)

    import shutil
    rxdata = os.path.join(game_dir, "Data", "Scripts.rxdata")
    backup = os.path.join(game_dir, "Data", "ScriptsBackup.rxdata")
    if not os.path.exists(backup):
        raise FileNotFoundError(
            f"找不到备份 {backup}，无法还原（原文件没有被替换过？）")

    scripts_dir = _scripts_dir(game_dir)
    if os.path.isdir(scripts_dir):
        shutil.rmtree(scripts_dir)
        say(f"[还原] 已删除 {scripts_dir}")

    with open(backup, "rb") as fsrc, open(rxdata, "wb") as fdst:
        fdst.write(fsrc.read())
    say(f"[还原] 已把备份恢复为 Scripts.rxdata（备份文件保留：{backup}）")
    say("[还原] 游戏已回到未解包状态；再点「提取脚本」可重新解包")
    log.info("还原提取：%s", game_dir)
    return {"ok": True}


