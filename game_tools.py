def _ttf_family_name(path):
    """
    从 TTF 的 name 表读字族名（优先 ID 16，其次 ID 1）。
    读不到返回 None。
    """
    try:
        with open(path, "rb") as f:
            data = f.read()
        if data[:4] not in (b"\x00\x01\x00\x00", b"true", b"OTTO"):
            return None
        num_tables = struct.unpack(">H", data[4:6])[0]
        name_off = None
        for i in range(num_tables):
            rec = data[12 + i * 16: 12 + i * 16 + 16]
            if rec[:4] == b"name":
                name_off = struct.unpack(">I", rec[8:12])[0]
                break
        if name_off is None:
            return None
        count = struct.unpack(">H", data[name_off + 2:name_off + 4])[0]
        str_off = name_off + struct.unpack(
            ">H", data[name_off + 4:name_off + 6])[0]
        found = {}
        for i in range(count):
            rec = data[name_off + 6 + i * 12: name_off + 6 + i * 12 + 12]
            platform, _enc, _lang, name_id = struct.unpack(
                ">HHHH", rec[:8])
            length, offset = struct.unpack(">HH", rec[8:12])
            if name_id in (1, 16) and name_id not in found:
                raw = data[str_off + offset: str_off + offset + length]
                try:
                    val = (raw.decode("utf-16-be") if platform in (0, 3)
                           else raw.decode("latin-1"))
                except Exception:
                    continue
                if val.strip():
                    found[name_id] = val.strip()
        return found.get(16) or found.get(1)
    except Exception as e:
        log.debug("读取字体族名失败：%s", e)
        return None


def font_family_name(path):
    """
    公开发布版：读取 TTF/OTF 的字族名（无法读取时返回 None）。
    插件植入前给用户预览字体信息用。
    """
    return _ttf_family_name(path)


def resolve_font(font_file=None):
    """
    确定植入时使用的字体，返回 (字体文件路径, 字族名, 输出提示行列表)。

    ★ 纯文件操作：不调用任何模型、不联网，只做「读 TTF 名字表 / 复制文件」。
    font_file 为空时用随程序分发的萝莉体。
    """
    notes = []
    path = font_file or config.FONT_FILE
    if not os.path.isfile(path):
        raise FileNotFoundError(f"字体文件不存在：{path}")
    family = _ttf_family_name(path) or config.FONT_NAME or "Lolita"
    notes.append(f"[插件] 字体：{os.path.basename(path)}（族名「{family}」）")
    return path, family, notes


def inject_cn_plugin(game_dir, emit=None, font_file=None):
    """
    植入中文文本处理插件（★ 纯文件写入，不调用模型）。

      1. 未解包过就先解包（会顺带装好加载器）；
      2. 写入 ~zz_ChineseTextSettings.rb / ~zz_ChineseTextRenderer.rb
         （~ 开头保证按文件名排序最后加载，能覆盖游戏自带函数）；
      3. 把选中的字体复制进游戏 Fonts 文件夹，字体名写进 Settings。

    ★ 只新增 / 覆盖这两个插件脚本与字体文件，不动游戏里其它任何脚本。
    font_file：用户自选的 TTF/OTF 路径；留空 = 内置萝莉体。
    返回 (植入的文件列表, 使用的字体族名)。
    """
    def say(msg):
        if emit:
            emit(msg)

    font_file, family, notes = resolve_font(font_file)
    for n in notes:
        say(n)

    # ★ 判据用「Data/Scripts 目录是否存在」：is_dumped() 对「rxdata 只剩
    #   加载器一条、目录却被删掉」的半吊子状态也会返回 True，会导致写到不存在的目录。
    if not os.path.isdir(_scripts_dir(game_dir)):
        say("[插件] 脚本尚未解包，先自动提取…")
        dump_scripts(game_dir, emit=emit)
    else:
        # 解包过但加载器可能被游戏还原，保险起见重写一次
        install_loader(game_dir)

    scripts_dir = _scripts_dir(game_dir)

    # 复制字体到游戏 Fonts 文件夹（mkxp-z 启动时会扫描该目录）
    fonts_dir = os.path.join(game_dir, "Fonts")
    os.makedirs(fonts_dir, exist_ok=True)
    font_dst = os.path.join(fonts_dir, os.path.basename(font_file))
    copied = os.path.abspath(font_dst) != os.path.abspath(font_file)
    if copied:
        with open(font_file, "rb") as fsrc, open(font_dst, "wb") as fdst:
            fdst.write(fsrc.read())
        say(f"[插件] 字体已复制：Fonts/{os.path.basename(font_file)}")

    settings_code = (
        "# Chinese text plugin - settings\n"
        "# Generated by the Pokemon translation tool.\n"
        # ★ 还原时靠这行判断字体是不是我们复制进去的（游戏自带的字体不能删）
        + (f"# Copied font: {os.path.basename(font_file)}\n" if copied
           else f"# Game font: {os.path.basename(font_file)}\n")
        + "module Settings\n"
        "\t# Vertical text offset (default 8; smaller value = lower text)\n"
        "\tY_OFFSET_OF_TEXT = 8\n\n"
        "\t# Command correction offset (default 8; smaller value = lower text)\n"
        "\tY_OFFSET_OF_ORDER_CORRCETION = 8\n\n"
        f"\t# Font family name (from {os.path.basename(font_file)})\n"
        f"\tGLOBAL_FONT_NAME = \"{family}\"\n"
        "end\n"
        "#=========================================================\n"
        "# Do not edit below this line.\n"
        "#=========================================================\n"
        "module MessageConfig\n"
        "  FONT_NAME                 = Settings::GLOBAL_FONT_NAME\n"
        "  SMALL_FONT_NAME           = Settings::GLOBAL_FONT_NAME\n"
        "  NARROW_FONT_NAME          = Settings::GLOBAL_FONT_NAME\n"
        "  FONT_Y_OFFSET             = Settings::Y_OFFSET_OF_TEXT\n"
        "  SMALL_FONT_Y_OFFSET       = Settings::Y_OFFSET_OF_TEXT\n"
        "  NARROW_FONT_Y_OFFSET      = Settings::Y_OFFSET_OF_TEXT\n"
        "end\n"
    )

    written = []
    for name, code in ((PLUGIN_SETTINGS_NAME, settings_code),
                       (PLUGIN_TOOLS_NAME, PLUGIN_TOOLS_CODE)):
        p = os.path.join(scripts_dir, name)
        with open(p, "w", encoding="utf-8", newline="") as f:
            f.write(code)
        written.append(name)
        say(f"[插件] 已写入 Scripts/{name}")

    say(f"[插件] 完成：游戏会通过加载器自动运行该插件，"
        f"中文将使用「{family}」逐字绘制")
    log.info("inject_cn_plugin：%s（字体 %s）", game_dir, family)
    return written, family


def restore_plugin(game_dir, emit=None):
    """
    还原「植入中文文本处理插件」：
      · 删掉 ~zz_ChineseTextSettings.rb / ~zz_ChineseTextRenderer.rb；
      · 当初复制进游戏 Fonts 的字体一并删掉（靠 Settings 里的
        「# Copied font: 」标记判断 —— 游戏自带的字体只会写
        「# Game font: 」，不会删）。
    只动这两个脚本与那一份字体，脚本解包状态与调试注入都不受影响。
    返回 {"removed": [...], "font": 字体文件名或 None, "found": bool}。
    """
    def say(msg):
        if emit:
            emit(msg)

    scripts_dir = _scripts_dir(game_dir)

    # ★ 先看标记：确认字体是我们复制进去的（游戏原有字体不能删）
    font_name = _plugin_copied_font(game_dir)

    removed, found = [], False
    for name in (PLUGIN_SETTINGS_NAME, PLUGIN_TOOLS_NAME):
        p = os.path.join(scripts_dir, name)
        if os.path.isfile(p):
            try:
                os.remove(p)
                removed.append(name)
                found = True
                say(f"[插件] 已删除 Scripts/{name}")
            except Exception as e:
                say(f"[插件] 删除 Scripts/{name} 失败：{e}")

    font_removed = _remove_copied_font(game_dir, font_name, say)
    if font_removed:
        removed.append(f"Fonts/{font_name}")

    if not found:
        say("[插件] 没有找到插件脚本（可能本来就没植入过）")
    else:
        say("[插件] 还原完成：插件脚本已删除"
            + ("，复制进去的字体也一并删除" if font_removed else ""))
    log.info("restore_plugin：%s → %s", game_dir, removed)
    return {"removed": removed, "font": font_name, "found": found}
