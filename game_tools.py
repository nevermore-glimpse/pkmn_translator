_ESCAPES = [("\\", "&bs;"), ("/", "&fs;"), (":", "&cn;"), ("*", "&as;"),
            ("?", "&qm;"), ('"', "&dq;"), ("<", "&lt;"), (">", "&gt;"),
            ("|", "&po;")]


def _title_to_filename(title):
    for ch, rep in _ESCAPES:
        title = title.replace(ch, rep)
    return title


def _digits(n, num=3):
    return str(n).zfill(num)


def _scripts_dir(game_dir):
    return os.path.join(game_dir, "Data", "Scripts")


def dump_scripts(game_dir, emit=None, force=False):
    """
    把 Data/Scripts.rxdata 解包为 Data/Scripts/*.rb，并写入「加载器」版
    Scripts.rxdata（原文件备份为 ScriptsBackup.rxdata）。

    ★ force=True：即使已解包过也重新提取（数据源用 ScriptsBackup.rxdata）。
      用于修复「解包后加载顺序被打乱」的游戏。

    返回 (提取的文件数, Scripts 目录, 已解包与否)。
    """
    def say(msg):
        if emit:
            emit(msg)

    rxdata = os.path.join(game_dir, "Data", "Scripts.rxdata")
    backup = os.path.join(game_dir, "Data", "ScriptsBackup.rxdata")
    if not os.path.exists(rxdata):
        raise FileNotFoundError(
            f"找不到 {rxdata} —— 请确认选择的是游戏根目录"
            f"（里面有 Data/Scripts.rxdata）")

    src = rxdata
    scripts = marshal_load_scripts(rxdata)
    if len(scripts) < 10:
        # ★ rxdata 只剩加载器一条 = 之前已经解包过；只要备份还在就按备份
        #   重新提取，否则「解包目录被删掉后」会卡在「已提取」的假状态里。
        if os.path.exists(backup):
            say("Scripts.rxdata 已是加载器版（脚本少于 10 条），"
                "检测到 ScriptsBackup.rxdata，自动按备份重新提取")
            src = backup
            scripts = marshal_load_scripts(backup)
        elif not force:
            say("Scripts.rxdata 看起来已经解包过（脚本少于 10 条），跳过提取")
            return 0, _scripts_dir(game_dir), True
    elif force:
        say("按备份 ScriptsBackup.rxdata 重新提取")

    path = _scripts_dir(game_dir)

    # 清空旧目录（只动 Data/Scripts，不碰别处）
    if os.path.isdir(path):
        import shutil
        shutil.rmtree(path)
    os.makedirs(path, exist_ok=True)

    folder_id = [1, 1]          # 最多两层文件夹
    file_id = 1
    level = 0
    folder_path = path
    folder_name = None
    written = 0

    order = []          # ★ 按原始顺序记录相对路径 → 写进加载顺序清单

    for i, (_sid, title, code) in enumerate(scripts):
        title = _title_to_filename(title).strip()
        code = code.replace("\r", "")
        if not title and not code:
            continue

        m = re.search(r"\[\[\s*(.+)\s*\]\]$", title)
        if m:                                  # 分组名 → 建文件夹
            section = (m.group(1) or "").strip() or "unnamed"
            folder_num = ("999" if i >= len(scripts) - 2
                          else _digits(folder_id[level]))
            folder_name = folder_num + "_" + section
            os.makedirs(os.path.join(folder_path, folder_name),
                        exist_ok=True)
            folder_id[level] += 1
            if level < len(folder_id) - 1:
                level += 1
                folder_id[level] = 1
                folder_path = os.path.join(folder_path, folder_name)
                folder_name = None
            file_id = 1
        elif title.startswith("====="):        # 回到根目录
            level = 0
            folder_path = path
            folder_name = None

        if not code:
            continue

        this_folder = folder_path
        if folder_name:
            this_folder = os.path.join(folder_path, folder_name)
        section = title.strip() or "unnamed"
        file_num = "999" if i >= len(scripts) - 1 else _digits(file_id)
        fname = file_num + "_" + section + ".rb"
        with open(os.path.join(this_folder, fname), "w",
                  encoding="utf-8", newline="") as f:
            f.write(code)
        order.append(os.path.relpath(os.path.join(this_folder, fname), path)
                     .replace("\\", "/"))
        file_id += 1
        written += 1

    # ★ 加载顺序清单：文件夹里的编号会从 001 重新开始，只按文件名排序会
    #   把原本靠后的脚本提前，导致 alias / 常量在定义之前被引用（NameError）
    with open(os.path.join(path, LOAD_ORDER_FILE), "w",
              encoding="utf-8", newline="") as f:
        f.write("# script load order (original Scripts.rxdata order)\n")
        f.write("\n".join(order) + "\n")

    # 备份原 rxdata
    backup = os.path.join(game_dir, "Data", "ScriptsBackup.rxdata")
    if not os.path.exists(backup) and src == rxdata:
        with open(rxdata, "rb") as fsrc, open(backup, "wb") as fdst:
            fdst.write(fsrc.read())

    # 用加载器替换 Scripts.rxdata
    install_loader(game_dir)

    say(f"[提取] 已解包 {written} 个脚本 → {path}")
    say(f"[提取] 已生成加载顺序清单 {LOAD_ORDER_FILE}"
        "（严格按原脚本顺序加载，避免 alias / 常量未定义）")
    say("[提取] Scripts.rxdata 已替换为加载器（原文件 → ScriptsBackup.rxdata），"
        "此后改动 rb 文件即时生效")
    log.info("dump_scripts：%s → %d 个脚本", game_dir, written)
    return written, path, False


def install_loader(game_dir):
    """把 Scripts.rxdata 替换成「加载器」版（先备份）。"""
    rxdata = os.path.join(game_dir, "Data", "Scripts.rxdata")
    backup = os.path.join(game_dir, "Data", "ScriptsBackup.rxdata")
    if not os.path.exists(backup):
        with open(rxdata, "rb") as fsrc, open(backup, "wb") as fdst:
            fdst.write(fsrc.read())
    entries = [[62054200, "Main", zlib.compress(LOADER_CODE.encode("utf-8"))]]
    data = marshal_dump_scripts(entries)
    tmp = rxdata + ".tmp"
    with open(tmp, "wb") as f:
        f.write(data)
    os.replace(tmp, rxdata)
    log.info("加载器已写入 %s（备份 %s）", rxdata, backup)


def is_dumped(game_dir):
    """是否已经解包（存在 Scripts 目录，或 rxdata 条目 < 10）。"""
    if os.path.isdir(_scripts_dir(game_dir)):
        return True
    rxdata = os.path.join(game_dir, "Data", "Scripts.rxdata")
    if not os.path.exists(rxdata):
        return False
    try:
        return len(marshal_load_scripts(rxdata)) < 10
    except Exception:
        return False


