def _rb_files(scripts_dir):
    out = []
    for root, _dirs, files in os.walk(scripts_dir):
        for f in files:
            if f.lower().endswith(".rb"):
                out.append(os.path.join(root, f))
    return sorted(out)


def _rel(path, scripts_dir):
    return os.path.relpath(path, scripts_dir).replace("\\", "/")


