def enable_debug(game_dir, mode="startfile", emit=None):
    """
    按选定方式开启调试（脚本需已提取）。
    返回 (modifications, report_path)。

    ★ 四种方式全部是「纯规则 / 纯文件写入」，一律不调用模型、不联网：
      ① startfile → 写 000_OpenDebug.rb
      ② unlock    → 用固定正则规则去掉 $DEBUG / $TEST 条件
      ③ repel     → 往 100 步除虫喷雾（:REPEL）处理块开头插询问
      ④ f9        → 写 ~zz_F9DebugHotkey.rb
    mode 取值见 DEBUG_MODES。
    """
    def say(msg):
        if emit:
            emit(msg)

    if mode not in DEBUG_MODE_KEYS:
        mode = "startfile"
    say(f"[调试] 注入方式：{debug_mode_of(mode)['label']}")

    modifications = []

    if mode == "startfile":
        base = enable_debug_base(game_dir, emit=emit)
        if base:
            modifications.append(base)
            say(f"[调试] 已写入 {DEBUG_SCRIPT_NAME}（$DEBUG = true）")
        else:
            modifications.append({
                "file": DEBUG_SCRIPT_NAME,
                "how": "已存在（本次保留）",
                "change": "$DEBUG = true / $TEST = true",
            })

    elif mode == "unlock":
        base = enable_debug_base(game_dir, emit=emit)
        if base:
            modifications.append(base)
            say(f"[调试] 已写入 {DEBUG_SCRIPT_NAME}（$DEBUG = true）")
        stripped = _strip_debug_conditions(game_dir)
        modifications.extend(stripped)
        if stripped:
            say(f"[调试] 已改写 {len(stripped)} 个文件里的 $DEBUG / $TEST 条件")
        else:
            say("[调试] 没找到需要改写的 $DEBUG / $TEST 条件"
                "（可能已经被改过，或该游戏靠 $DEBUG 以外的方式控制）")

    elif mode == "repel":
        injected = _inject_repel(game_dir)
        if injected:
            modifications.extend(injected)
            say(f"[调试] 已注入 {injected[0]['file']}（100 步除虫喷雾）")
        else:
            say("[调试] 没找到 :REPEL（100 步除虫喷雾）处理块；"
                "可换用方式①或④")

    elif mode == "f9":
        modifications.extend(_inject_f9(game_dir))
        say(f"[调试] 已写入 {F9_SCRIPT_NAME}（F9 打开调试菜单）")

    say("[调试] 该方式已完成")
    report = write_debug_report(game_dir, modifications, [], [], mode=mode)
    say(f"[调试] 修改说明已输出：{report}")
    return modifications, report


